"""
Export an OpenEar temporal bone segmentation to printable STL surface models.

Usage (headless):
  OPENEAR_DIR=./openear_ZETA STL_OUT=./openear_ZETA_stl OPENEAR_SPECIMEN=ZETA \
  Slicer --no-splash --no-main-window --python-script export_openear_stl.py

Optional environment variables:
  STL_SMOOTHING      closed-surface smoothing factor (default 0.3)
  STL_MAX_TRIANGLES  meshes above this are decimated to it (default 400000)

Steps
  1. Load Segmentation.seg.nrrd (0.125 mm voxels) from fetch_openear.py.
  2. Convert every segment to a closed surface (Slicer's flying edges +
     windowed-sinc smoothing).
  3. Decimate meshes larger than STL_MAX_TRIANGLES (quadric decimation with
     volume preservation); in OpenEar this applies to Bone and Sinus/Dura.
  4. Triangulate and write binary STL in millimetres, RAS coordinates, one
     file per segment, all in one shared frame.
  5. Report open / non-manifold edges per mesh and write README.txt with
     source, license and units.

Data: Sieber D, et al. Sci Data 6:180297 (2019); Zenodo 1473724; CC BY 4.0.
"""
import os
import sys
import traceback

import slicer
import vtk

DATA = os.environ.get("OPENEAR_DIR", os.getcwd())
OUT = os.environ.get("STL_OUT", os.path.join(DATA, "stl"))
SPECIMEN = os.environ.get("OPENEAR_SPECIMEN", "OpenEar")
SMOOTHING = os.environ.get("STL_SMOOTHING", "0.3")
MAX_TRIS = int(os.environ.get("STL_MAX_TRIANGLES", "400000"))


def open_edges(pd):
    fe = vtk.vtkFeatureEdges()
    fe.SetInputData(pd)
    fe.BoundaryEdgesOn()
    fe.NonManifoldEdgesOn()
    fe.FeatureEdgesOff()
    fe.ManifoldEdgesOff()
    fe.Update()
    return fe.GetOutput().GetNumberOfCells()


def main():
    os.makedirs(OUT, exist_ok=True)
    segNode = slicer.util.loadSegmentation(os.path.join(DATA, "Segmentation.seg.nrrd"))
    seg = segNode.GetSegmentation()
    seg.SetConversionParameter("Smoothing factor", SMOOTHING)
    segNode.CreateClosedSurfaceRepresentation()

    rows = []
    for n in range(seg.GetNumberOfSegments()):
        sid = seg.GetNthSegmentID(n)
        name = seg.GetSegment(sid).GetName()
        pd = vtk.vtkPolyData()
        segNode.GetClosedSurfaceRepresentation(sid, pd)
        tri = vtk.vtkTriangleFilter()
        tri.SetInputData(pd)
        tri.Update()
        mesh = tri.GetOutput()
        if mesh.GetNumberOfCells() > MAX_TRIS:
            dec = vtk.vtkQuadricDecimation()
            dec.SetInputData(mesh)
            dec.SetTargetReduction(1.0 - MAX_TRIS / float(mesh.GetNumberOfCells()))
            dec.VolumePreservationOn()
            dec.Update()
            mesh = dec.GetOutput()
        safe = "".join(c if c.isalnum() else "_" for c in name).strip("_")
        fn = os.path.join(OUT, "%s_%02d_%s.stl" % (SPECIMEN, n, safe))
        w = vtk.vtkSTLWriter()
        w.SetFileTypeToBinary()
        w.SetFileName(fn)
        w.SetInputData(mesh)
        w.Write()
        b = mesh.GetBounds()
        row = (os.path.basename(fn), name, b[1] - b[0], b[3] - b[2], b[5] - b[4],
               mesh.GetNumberOfCells(), open_edges(mesh))
        rows.append(row)
        print("STL %-45s %-26s %5.1f x %5.1f x %5.1f mm  %8d tris  open edges %d" % row)
        sys.stdout.flush()

    with open(os.path.join(OUT, "README.txt"), "w") as f:
        f.write("OpenEar specimen %s - STL surface models\n" % SPECIMEN)
        f.write("Source: Sieber D, et al. The OpenEar library of 3D models of the human temporal bone\n"
                "based on computed tomography and micro-slicing. Sci Data 6:180297 (2019).\n"
                "Zenodo record 1473724. License: CC BY 4.0 (attribution required).\n\n")
        f.write("Generated by SlicerTemporalBoneSafety/TemporalBoneSafety/Testing/export_openear_stl.py\n"
                "from 06_Segmentation/Segmentation.seg.nrrd: closed-surface conversion (smoothing %s),\n"
                "meshes above %d triangles decimated (quadric, volume preserving).\n"
                "Units: millimetres. Coordinates: RAS (3D Slicer world; same frame as the CBCT).\n"
                "All files share one frame; load them together without moving them.\n"
                "Run your printer software's mesh repair before printing. Not for clinical use.\n\n"
                % (SMOOTHING, MAX_TRIS))
        f.write("file, structure, size x/y/z (mm), triangles, open/non-manifold edges\n")
        for r in rows:
            f.write("%s, %s, %.1f/%.1f/%.1f, %d, %d\n" % r)
    print("Wrote %d STL files to %s" % (len(rows), OUT))


try:
    main()
    code = 0
except Exception:
    traceback.print_exc()
    code = 1
sys.stdout.flush()
if os.environ.get("TBS_EXIT", "1") == "1":
    slicer.util.exit(code)
